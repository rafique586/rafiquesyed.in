import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const articlesDirectory = path.join(root, 'content', 'articles');
const outputFile = path.join(root, 'lib', 'generated-articles.ts');

function parseFrontMatter(source, filename) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) throw new Error(`${filename}: missing front matter`);

  const attributes = {};
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const separator = line.indexOf(':');
    if (separator === -1) throw new Error(`${filename}: invalid front matter line: ${line}`);
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    attributes[key] = value;
  }

  const required = ['title', 'description', 'topic', 'date'];
  for (const key of required) {
    if (!attributes[key]) throw new Error(`${filename}: front matter requires ${key}`);
  }

  const slug = filename.replace(/\.md$/, '');
  return {
    slug,
    title: attributes.title,
    description: attributes.description,
    topic: attributes.topic,
    date: attributes.date,
    displayDate: attributes.displayDate || attributes.date,
    fieldNote: attributes.fieldNote || 'Field note',
    marginNote: attributes.marginNote || '',
    visual: attributes.visual || '',
    draft: attributes.draft === 'true',
    body: match[2].trim(),
  };
}

const filenames = (await readdir(articlesDirectory))
  .filter((name) => name.endsWith('.md') && !name.startsWith('_') && name !== 'README.md')
  .sort();

const articles = [];
for (const filename of filenames) {
  const source = await readFile(path.join(articlesDirectory, filename), 'utf8');
  const article = parseFrontMatter(source, filename);
  if (!article.draft) articles.push(article);
}

articles.sort((a, b) => b.date.localeCompare(a.date));

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(
  outputFile,
  `// Generated by scripts/generate-articles.mjs. Do not edit directly.\n\nexport type GeneratedArticle = {\n  slug: string;\n  title: string;\n  description: string;\n  topic: string;\n  date: string;\n  displayDate: string;\n  fieldNote: string;\n  marginNote: string;\n  visual: string;\n  body: string;\n};\n\nexport const generatedArticles: GeneratedArticle[] = ${JSON.stringify(articles, null, 2)};\n`,
);

console.log(`Generated ${articles.length} published article(s).`);
